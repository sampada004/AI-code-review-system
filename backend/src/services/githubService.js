const githubAccountModel = require("../models/githubAccountModel");
const encryption = require("../utils/encryption");

async function getGithubToken(userId) {
  const githubAccount = await githubAccountModel.findByUserId(userId);
  if (githubAccount && githubAccount.encrypted_access_token) {
    const token = encryption.decryptToken(githubAccount.encrypted_access_token);
    if (token) return token;
  }
  return process.env.GITHUB_TOKEN; // fallback
}

async function fetchGitHubAPI(endpoint, method, token, body = null) {
  const url = `https://api.github.com${endpoint}`;
  const options = {
    method,
    headers: {
      Authorization: `Bearer ${token}`,
      Accept: "application/vnd.github.v3+json",
      "Content-Type": "application/json",
      "User-Agent": "Inspectra-AI",
    },
  };
  
  if (body) {
    options.body = JSON.stringify(body);
  }

  const res = await fetch(url, options);
  const data = await res.json().catch(() => ({}));
  
  if (!res.ok) {
    throw new Error(`GitHub API Error (${res.status}): ${data.message || res.statusText}`);
  }
  
  return data;
}

async function createPullRequest({ userId, repoName, baseBranch, filePath, newContent, files, title, body, customBranchName }) {
  const token = await getGithubToken(userId);
  if (!token) {
    throw new Error("No GitHub token found. Please connect your GitHub account.");
  }

  // Normalize files list: either array of files or single file
  let filesToCommit = [];
  if (Array.isArray(files) && files.length > 0) {
    filesToCommit = files.filter(f => f && f.filePath && f.newContent != null);
  } else if (filePath && newContent != null) {
    filesToCommit = [{ filePath, newContent }];
  }

  if (filesToCommit.length === 0) {
    throw new Error("No files provided for pull request creation.");
  }

  const branchName = customBranchName || `inspectra/fix-${filesToCommit.length > 1 ? 'batch' : 'issues'}-${Date.now()}`;

  // 1. Get the SHA of the latest commit on the base branch
  const refData = await fetchGitHubAPI(`/repos/${repoName}/git/ref/heads/${baseBranch}`, "GET", token);
  const baseCommitSha = refData.object.sha;

  // 2. Get the commit to find its tree SHA
  const commitData = await fetchGitHubAPI(`/repos/${repoName}/git/commits/${baseCommitSha}`, "GET", token);
  const baseTreeSha = commitData.tree.sha;

  // 3. Create a new branch reference
  await fetchGitHubAPI(`/repos/${repoName}/git/refs`, "POST", token, {
    ref: `refs/heads/${branchName}`,
    sha: baseCommitSha
  });

  // 4. Create blobs for each modified file
  const treeEntries = await Promise.all(
    filesToCommit.map(async (file) => {
      const blobData = await fetchGitHubAPI(`/repos/${repoName}/git/blobs`, "POST", token, {
        content: file.newContent,
        encoding: "utf-8"
      });
      return {
        path: file.filePath,
        mode: "100644", // File (blob)
        type: "blob",
        sha: blobData.sha
      };
    })
  );

  // 5. Create a new tree with all updated files
  const treeData = await fetchGitHubAPI(`/repos/${repoName}/git/trees`, "POST", token, {
    base_tree: baseTreeSha,
    tree: treeEntries
  });

  // 6. Create a new commit
  const defaultCommitMessage = filesToCommit.length === 1
    ? `AI Code Review Fixes for ${filesToCommit[0].filePath}`
    : `AI Code Review Fixes for ${filesToCommit.length} files`;

  const newCommitData = await fetchGitHubAPI(`/repos/${repoName}/git/commits`, "POST", token, {
    message: title || defaultCommitMessage,
    tree: treeData.sha,
    parents: [baseCommitSha]
  });

  // 7. Update the branch reference to point to the new commit
  await fetchGitHubAPI(`/repos/${repoName}/git/refs/heads/${branchName}`, "PATCH", token, {
    sha: newCommitData.sha,
    force: true
  });

  // 8. Open the Pull Request
  const defaultPrBody = filesToCommit.length === 1
    ? `Applied AI-suggested fixes to improve code quality in \`${filesToCommit[0].filePath}\`.`
    : `Applied AI-suggested fixes across ${filesToCommit.length} files:\n\n` +
      filesToCommit.map(f => `- \`${f.filePath}\``).join("\n") +
      `\n\nAutomated PR generated by Inspectra AI.`;

  const prData = await fetchGitHubAPI(`/repos/${repoName}/pulls`, "POST", token, {
    title: title || defaultCommitMessage,
    body: body || defaultPrBody,
    head: branchName,
    base: baseBranch
  });

  return {
    prUrl: prData.html_url,
    prNumber: prData.number,
    branchName,
    filesCount: filesToCommit.length,
    files: filesToCommit.map(f => f.filePath)
  };
}

module.exports = {
  createPullRequest
};
